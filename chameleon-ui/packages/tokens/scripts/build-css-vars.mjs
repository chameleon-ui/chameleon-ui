import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderDensityCss } from "./density-css.mjs";
import { compileTokenDirectory, TokenCompilerError } from "./token-compiler.mjs";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDirectory = path.join(packageRoot, "src", "core");
const buildDirectory = path.join(packageRoot, "dist", "css");
const distDirectory = path.join(packageRoot, "dist");

const HEADER = "/* Generated by @chameleon-ui/tokens. Do not edit. */";

function cssLength(value) {
  if (typeof value === "string") return value;
  if (value && typeof value === "object" && typeof value.value === "number") {
    return `${value.value}${value.unit}`;
  }
  throw new TokenCompilerError(
    "tokens.json",
    `expected a resolved dimension, got ${JSON.stringify(value)}`,
    "keep dimension tokens as DTCG dimension objects",
  );
}

/**
 * Flat resolved token map for JS/TS consumers (name -> CSS scalar string).
 *
 * @complexity time O(n) | space O(n) | n = token count
 * @guarantees deterministic key order (compile order is sorted)
 */
function renderTokensJson(compiled) {
  const flat = {};
  for (const token of compiled.tokens) {
    flat[token.path.join(".")] =
      typeof token.value === "object" && token.value !== null && "unit" in token.value
        ? cssLength(token.value)
        : token.value;
  }
  return `${JSON.stringify(flat, null, 2)}\n`;
}

async function loadStyleDictionary() {
  try {
    const module = await import("style-dictionary");
    return module.default;
  } catch (error) {
    throw new TokenCompilerError(
      "packages/tokens/package.json",
      `Style Dictionary is unavailable: ${error instanceof Error ? error.message : String(error)}`,
      "run pnpm install once from the chameleon-ui monorepo root, then rerun this build",
    );
  }
}

async function main() {
  const compiled = await compileTokenDirectory(sourceDirectory);
  const StyleDictionary = await loadStyleDictionary();
  const formatName = "chameleon/css-variables-deterministic";

  StyleDictionary.registerFormat({
    name: formatName,
    format: () => compiled.css,
  });

  // Style Dictionary receives already-resolved DTCG tokens so its only write is
  // the reviewed deterministic string. It remains the selected O2 build engine.
  const dictionary = new StyleDictionary({
    log: { verbosity: "silent", warnings: "disabled" },
    tokens: compiled.dtcg,
    usesDtcg: true,
    platforms: {
      css: {
        buildPath: `${buildDirectory}${path.sep}`,
        files: [
          {
            destination: "variables.css",
            format: formatName,
            options: { showFileHeader: false },
          },
        ],
      },
    },
  });

  await dictionary.buildAllPlatforms();

  await writeFile(path.join(buildDirectory, "density.css"), renderDensityCss(compiled), "utf8");
  await writeFile(path.join(distDirectory, "tokens.json"), renderTokensJson(compiled), "utf8");

  console.log(
    `[@chameleon-ui/tokens] wrote ${compiled.tokens.length} variables to dist/css/variables.css`,
  );
  console.log("[@chameleon-ui/tokens] wrote dist/css/density.css and dist/tokens.json");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
