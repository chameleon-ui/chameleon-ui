function flattenMessages(value, prefix = '') {
  if (typeof value === 'string') return { [prefix]: value }
  return Object.fromEntries(
    Object.entries(value).flatMap(([key, nested]) =>
      Object.entries(flattenMessages(nested, prefix ? `${prefix}.${key}` : key)),
    ),
  )
}

function unflattenMessages(flat) {
  const root = {}
  for (const [key, value] of Object.entries(flat)) {
    const parts = key.split('.')
    let cursor = root
    for (let index = 0; index < parts.length - 1; index += 1) {
      const part = parts[index]
      cursor[part] ??= {}
      cursor = cursor[part]
    }
    cursor[parts[parts.length - 1]] = value
  }
  return root
}

async function main() {
  const catalog = JSON.parse(await readFile(catalogPath, 'utf8'))
  let written = 0
  let skipped = 0

  for (const component of catalog.components) {
    const localeDir = path.join(componentsSrc, component.slug, 'locales')
    await mkdir(localeDir, { recursive: true })
    const english = flattenMessages(
      JSON.parse(await readFile(path.join(localeDir, 'en.json'), 'utf8')),
    )

    const missingKeys = Object.keys(english).filter((key) => {
      const table = TRANSLATIONS[key]
      return !table || NEW_LOCALES.some((locale) => !table[locale])
    })
    if (missingKeys.length > 0) {
      skipped += 1
      continue
    }

    for (const locale of NEW_LOCALES) {
      const translated = {}
      for (const [key, englishText] of Object.entries(english)) {
        translated[key] = TRANSLATIONS[key][locale]
      }
      const nested = unflattenMessages(translated)
      const outPath = path.join(localeDir, `${locale}.json`)
      await writeFile(outPath, `${JSON.stringify(nested, null, 2)}\n`, 'utf8')
      written += 1
    }
  }

  console.log(
    `[generate-phase2-locales] wrote ${written} locale files; skipped ${skipped} components with keys outside TRANSLATIONS`,
  )
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
