/**
 * Generate one MDX page per catalog slug plus a typed contract map.
 *
 * Wrappers in docs/components/<slug>.mdx are mechanical and always overwritten.
 * Hand-authored live MDX narratives live in docs/components/_gold/<slug>.mdx and
 * are imported, never generated. GOLD is the original 8; LIVE is the extra
 * high-traffic set with ```jsx live``` playgrounds. API tables are NOT inlined
 * here — ComponentPage reads contract.json via src/generated/contracts.ts.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const docsRoot = join(here, '..')
const componentsRoot = dirname(require.resolve('@chameleon-ui/components/catalog.json'))
const catalog = JSON.parse(await readFile(join(componentsRoot, 'catalog.json'), 'utf8'))

const GOLD = new Set(['button', 'input', 'select', 'dialog', 'table', 'tabs', 'form', 'card'])
const LIVE = new Set([
  'accordion',
  'combobox',
  'drawer',
  'pagination',
  'slider',
  'date-picker',
  'data-grid',
  'chat-bubble',
  'sparkline',
  'action-sheet',
])
const LIVE_MDX = new Set([...GOLD, ...LIVE])

function ident(slug) {
  return `c_${slug.replace(/[^a-zA-Z0-9]/g, '_')}`
}

const outDocs = join(docsRoot, 'docs', 'components')
const outGen = join(docsRoot, 'src', 'generated')
await mkdir(outDocs, { recursive: true })
await mkdir(outGen, { recursive: true })

const importLines = [
  '/* Generated by scripts/generate-component-mdx.mjs — do not edit. */',
  "import type { ContractDoc } from '../contracts'",
]
const mapLines = ['export const CONTRACTS: Record<string, ContractDoc> = {']

for (const item of catalog.components) {
  const name = ident(item.slug)
  const rel = `@chameleon-ui/components/contracts/${item.slug}`
  importLines.push(`import ${name} from '${rel}'`)
  // JSON module imports widen literal unions (e.g. exports.kind) to string;
  // assert ContractDoc so tsc --noEmit accepts the generated map.
  mapLines.push(`  '${item.slug}': ${name} as ContractDoc,`)
}

mapLines.push('}')
mapLines.push('')

await writeFile(join(outGen, 'contracts.ts'), `${importLines.join('\n')}\n\n${mapLines.join('\n')}`, 'utf8')
await writeFile(
  join(outGen, 'README.md'),
  '# Generated docs bindings\n\nDo not edit. Regenerated by `scripts/generate-component-mdx.mjs` from `catalog.json` + `contract.json`.\n',
  'utf8',
)

for (const item of catalog.components) {
  const slug = item.slug
  const title = item.name ?? slug
  const purpose = JSON.stringify(item.requirement ?? '')
  const goldImport = LIVE_MDX.has(slug)
    ? `import Gold from './_gold/${slug}.mdx';\n`
    : ''
  const goldBody = LIVE_MDX.has(slug) ? '\n<Gold />\n' : ''
  const playgroundProp = LIVE_MDX.has(slug) ? ' includePlayground={false}' : ''

  const mdx = `---
id: ${slug}
title: ${title}
sidebar_label: ${title}
description: ${purpose}
---

import ComponentPage from '@site/src/components/ComponentPage';
${goldImport}
# ${title}
${goldBody}
<ComponentPage slug="${slug}"${playgroundProp} />
`

  await writeFile(join(outDocs, `${slug}.mdx`), mdx, 'utf8')
}

await writeFile(
  join(outGen, 'slugs.json'),
  `${JSON.stringify(
    {
      generatedAt: new Date().toISOString(),
      count: catalog.components.length,
      gold: [...GOLD],
      live: [...LIVE],
      slugs: catalog.components.map((item) => item.slug),
    },
    null,
    2,
  )}\n`,
  'utf8',
)

console.log(`docs mdx: ${catalog.components.length} pages (${GOLD.size} gold, ${LIVE.size} live)`)
